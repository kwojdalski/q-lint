"""Write editors/vscode/syntaxes/q.tmLanguage.json, the q syntax colouring.

A TextMate grammar is how VS Code colours Python, and every other language
it ships: a set of regular expressions that tag spans of text with scope
names (`comment.line`, `string.quoted`, `support.function`, ...) which the
colour theme then paints. Like the linter, it reads the source and never runs
it.

The builtin names come from src/reserved.json, the list the rules already
use, so this is generated rather than written by hand:

    python3 scripts/q_grammar.py > editors/vscode/syntaxes/q.tmLanguage.json

`tests/q_grammar.rs` fails when the committed file is stale.

What it gets right is the lexical shape q shares with the linter's own views
in src/lib.rs: a `/` opens a comment only at the start of a line or after
whitespace, a line holding a lone `/` opens a block that a lone `\\` closes,
a lone `\\` outside a block ends the script, a line opening with `\\` is a
system command, and `p)` / `k)` lines are another language.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

CONTROL = ["if", "do", "while"]
QSQL = ["select", "exec", "update", "delete", "from", "by", "where"]

# An identifier edge: not preceded or followed by a name character, a dot
# (so `.q.count` is not `count`) or a backtick (so `` `count `` is a symbol).
# An underscore before one is no edge to stop at: a name cannot start with
# `_`, and one inside a name (`a_b`, `` `a_b ``) is taken with the name before
# anything is looked for after it, so an `_` that is reached is drop or cut -
# `1_til 5`, `f[x]_y`, `x _y`.
BEFORE = r"(?<![A-Za-z0-9.`])"
AFTER = r"(?![A-Za-z0-9_])"
# Where a number, temporal or null ends: `1_x` is 1, drop, x, since no
# literal holds an underscore.
LITERAL_END = r"(?![A-Za-z0-9])"
# Where a number or a temporal ends. q reads digits, letters and dots as one
# token, and colons with them once it is shaped like a time, and then refuses
# what is no literal - 1.5i, 1.2.3, 2024.01.02t, 12:34z - so nothing short of
# the whole token is a number. One digit before a colon is still a number:
# 0:, 1: and 2: are the file operators, as in `:f 0:x.
NUMBER_END = r"(?![A-Za-z0-9.]|(?<=\d\d):\d)"
TEMPORAL_END = r"(?![A-Za-z0-9.:])"
# The clock of a timestamp, datetime or timespan, and what follows the hours
# of a time: 12, 12:34, 12:34:56, 12:34:56.789.
MINUTES = r":\d{2}(?::\d{2}(?:\.\d*)?)?"
CLOCK = r"\d{2}(?:" + MINUTES + r")?"
NAME = r"\.?[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z0-9_]+)*"
# A dotted name split in two: the namespace `.ns.sub` and the member `.f`.
# The first group is empty for a name with no leading dot, so `a.b` and `f`
# stay whole in the second.
SPLIT = r"(\.[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z0-9_]+)*(?=\.))?(" + NAME + ")"
NAMESPACE = {"name": "entity.name.namespace.q"}
PARAMETERS = [
    {"match": r"[A-Za-z][A-Za-z0-9_]*", "name": "variable.parameter.q"},
    {"match": ";", "name": "punctuation.separator.parameters.q"},
]


def words(names):
    return BEFORE + "(?:" + "|".join(sorted(names, key=lambda n: (-len(n), n))) + ")" + AFTER


def grammar():
    reserved = json.loads((ROOT / "src" / "reserved.json").read_text())
    builtins = [n for n in reserved if n not in CONTROL and n not in QSQL]
    missing = [n for n in CONTROL + QSQL if n not in reserved]
    assert not missing, f"not in reserved.json: {missing}"

    expression = [
        {"include": "#comment"},
        {"include": "#string"},
        {"include": "#symbol"},
        {"include": "#lambda"},
        {"include": "#number"},
        {"include": "#definition"},
        {"include": "#flow"},
        {"include": "#keyword"},
        {"include": "#system-namespace"},
        {"include": "#builtin"},
        {"include": "#name"},
        {"include": "#operator"},
    ]

    # A lambda's body. A lone `/` or `\\` is read by the script loader line by
    # line, so it opens a block or ends the script inside a lambda too.
    def body(implicit):
        return (
            [{"include": "#block-comment"}, {"include": "#end-of-script"}]
            + expression[:6]
            + (
                [
                    {
                        "comment": "x, y and z are a lambda's implicit parameters.",
                        "match": BEFORE + "[xyz]" + AFTER,
                        "name": "variable.language.implicit.q",
                    }
                ]
                if implicit
                else []
            )
            + expression[6:]
        )

    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "name": "q",
        "scopeName": "source.q",
        "comment": "Generated by scripts/q_grammar.py from src/reserved.json - edit that, not this.",
        "patterns": [
            {
                "comment": "q skips a script's first line when it opens #!, so an executable "
                "script starts #!/usr/bin/env q. Only the first: on any other line it is code.",
                "match": r"\A#!.*$",
                "name": "comment.line.shebang.q",
            },
            {"include": "#block-comment"},
            {"include": "#end-of-script"},
            {"include": "#foreign"},
            {"include": "#system-command"},
            {"include": "#prompt"},
            {"include": "#expression"},
        ],
        "repository": {
            "block-comment": {
                "name": "comment.block.q",
                "begin": r"^/\s*$",
                "end": r"^\\\s*$",
                "beginCaptures": {"0": {"name": "punctuation.definition.comment.begin.q"}},
                "endCaptures": {"0": {"name": "punctuation.definition.comment.end.q"}},
                "patterns": [{"include": "#qdoc"}],
            },
            "end-of-script": {
                "comment": "A lone backslash outside a block ends the script; q reads nothing after it.",
                "name": "comment.block.end-of-script.q",
                "begin": r"^\\\s*$",
                "end": r"(?=A)(?!A)",
                "beginCaptures": {"0": {"name": "punctuation.definition.comment.begin.q"}},
            },
            "foreign": {
                "comment": "p) and k) lines, and the indented lines that continue them, across blank lines as q reads them.",
                "patterns": [
                    {
                        "name": "meta.embedded.block.python.q",
                        "begin": r"^(p\))",
                        "end": r"^(?=\S)",
                        "beginCaptures": {"1": {"name": "keyword.other.language-prefix.q"}},
                        "contentName": "source.python",
                        "patterns": [{"include": "source.python"}],
                    },
                    {
                        "name": "meta.embedded.block.k.q",
                        "begin": r"^(k\))",
                        "end": r"^(?=\S)",
                        "beginCaptures": {"1": {"name": "keyword.other.language-prefix.q"}},
                        "contentName": "source.k",
                        "patterns": [{"include": "source.k"}],
                    },
                ],
            },
            "system-command": {
                "patterns": [
                    {
                        "match": r"^(\\d)\s+(\.[A-Za-z0-9_.]*)",
                        "captures": {
                            "1": {"name": "keyword.other.system.q"},
                            "2": {"name": "entity.name.namespace.q"},
                        },
                    },
                    {
                        "match": r"^(\\[A-Za-z_12]\w*|\\\\)(.*)$",
                        "captures": {
                            "1": {"name": "keyword.other.system.q"},
                            "2": {"name": "string.unquoted.argument.q"},
                        },
                    },
                ],
            },
            "prompt": {"match": r"^q\)", "name": "punctuation.separator.prompt.q"},
            "expression": {"patterns": expression},
            "comment": {
                "patterns": [
                    {
                        "comment": "qdoc: `///` opens a documentation block and `//` continues it.",
                        "name": "comment.line.documentation.q",
                        "begin": r"(?:^|(?<=\s))(//+)",
                        "end": r"$",
                        "beginCaptures": {"1": {"name": "punctuation.definition.comment.q"}},
                        "patterns": [{"include": "#qdoc"}],
                    },
                    {
                        "name": "comment.line.q",
                        "begin": r"(?:^|(?<=\s))(/)",
                        "end": r"$",
                        "beginCaptures": {"1": {"name": "punctuation.definition.comment.q"}},
                        "patterns": [{"include": "#qdoc"}],
                    },
                ],
            },
            "qdoc": {
                "patterns": [
                    {
                        "match": r"(@param)\s+([A-Za-z][A-Za-z0-9_]*)(?:\s+(\{[^}]*\}))?",
                        "captures": {
                            "1": {"name": "storage.type.class.qdoc.q"},
                            "2": {"name": "variable.parameter.qdoc.q"},
                            "3": {"name": "entity.name.type.qdoc.q"},
                        },
                    },
                    {
                        "match": r"(@[A-Za-z]+)(?:\s+(\{[^}]*\}))?",
                        "captures": {
                            "1": {"name": "storage.type.class.qdoc.q"},
                            "2": {"name": "entity.name.type.qdoc.q"},
                        },
                    },
                ],
            },
            "string": {
                "name": "string.quoted.double.q",
                "begin": '"',
                "end": '"',
                "beginCaptures": {"0": {"name": "punctuation.definition.string.begin.q"}},
                "endCaptures": {"0": {"name": "punctuation.definition.string.end.q"}},
                "patterns": [
                    {
                        "comment": "What q takes after a backslash: n, r, t, a quote, a backslash, "
                        "a slash, or three octal digits up to \\377 - \\400 is refused.",
                        "match": r'\\(?:[0-3][0-7]{2}|[nrt"\\/])',
                        "name": "constant.character.escape.q",
                    },
                    {"match": r"\\.", "name": "invalid.illegal.escape.q"},
                ],
            },
            "symbol": {
                "patterns": [
                    {
                        "comment": "A file or network handle: `:path/to/file, `:host:port. "
                        "A minus is not in one: `:a-b is `:a minus b.",
                        "match": r"`:[A-Za-z0-9_.:/]*",
                        "name": "constant.other.symbol.handle.q",
                    },
                    {
                        "comment": "Past a colon a symbol takes slashes too: `a:b/c is one symbol.",
                        "match": r"`[A-Za-z0-9_.]*(?::[A-Za-z0-9_.:/]*)?",
                        "name": "constant.other.symbol.q",
                    },
                ],
            },
            "lambda": {
                "comment": "x, y and z are a lambda's implicit parameters only when it declares "
                "none: in {[a] x+a} x is a global. So a lambda with a parameter list, on one "
                "line or several, is told from one without.",
                "patterns": [
                    {
                        "name": "meta.function.lambda.q",
                        "begin": r"(\{)\s*(\[)([^\]]*)(\])",
                        "end": r"\}",
                        "beginCaptures": {
                            "1": {"name": "punctuation.section.function.begin.q"},
                            "2": {"name": "punctuation.definition.parameters.begin.q"},
                            "3": {"patterns": PARAMETERS},
                            "4": {"name": "punctuation.definition.parameters.end.q"},
                        },
                        "endCaptures": {"0": {"name": "punctuation.section.function.end.q"}},
                        "patterns": body(implicit=False),
                    },
                    {
                        "comment": "A parameter list that closes on a later line.",
                        "name": "meta.function.lambda.q",
                        "begin": r"(\{)\s*(\[)",
                        "end": r"\}",
                        "beginCaptures": {
                            "1": {"name": "punctuation.section.function.begin.q"},
                            "2": {"name": "punctuation.definition.parameters.begin.q"},
                        },
                        "endCaptures": {"0": {"name": "punctuation.section.function.end.q"}},
                        "patterns": [
                            {
                                "begin": r"\G",
                                "end": r"\]",
                                "endCaptures": {"0": {"name": "punctuation.definition.parameters.end.q"}},
                                "patterns": [{"include": "#comment"}] + PARAMETERS,
                            }
                        ]
                        + body(implicit=False),
                    },
                    {
                        "name": "meta.function.lambda.q",
                        "begin": r"\{",
                        "end": r"\}",
                        "beginCaptures": {"0": {"name": "punctuation.section.function.begin.q"}},
                        "endCaptures": {"0": {"name": "punctuation.section.function.end.q"}},
                        "patterns": body(implicit=True),
                    },
                ],
            },
            "number": {
                "patterns": [
                    {
                        "comment": "Each shape with the type letters q reads as part of it, so "
                        "12:34:56.789p and 2024.01.02n are one literal. As KDB-X takes them; "
                        "what q refuses (2024.01.02t, 12:34z, 1Dt) is left uncoloured.",
                        "name": "constant.numeric.temporal.q",
                        "match": BEFORE
                        + "(?:"
                        + "|".join(
                            [
                                # timestamp: a timespan (n), date (d) or datetime (z) on request
                                r"\d{4}\.\d{2}\.\d{2}D(?:" + CLOCK + r")?[npdz]?",
                                # datetime: n and p only once it has minutes
                                r"\d{4}\.\d{2}\.\d{2}T(?:\d{2}" + MINUTES + r"[npdz]?|(?:\d{2})?[dz]?)",
                                # date, as itself or a timestamp (p), datetime (z), month (m)
                                # or timespan (n); and a month
                                r"\d{4}\.\d{2}(?:\.\d{2}[npdzm]?|m)",
                                # timespan, or the timestamp that far past 2000 (p)
                                r"\d+D(?:" + CLOCK + r")?[np]?",
                                # time, minute, second: a fraction of any length, and
                                # past three places a timespan (12:00:00.123456789)
                                r"\d{2}" + MINUTES + r"[nuvtp]?",
                                # past 99 hours: no timespan or timestamp
                                r"\d{3,}" + MINUTES + r"[uvt]?",
                            ]
                        )
                        + ")"
                        + TEMPORAL_END,
                    },
                    {
                        "comment": "A typed null or infinity. None is of symbol (the null symbol "
                        "is a lone backtick) and no infinity of guid: q refuses 0Ns, 0Ws and 0Wg.",
                        "name": "constant.language.null.q",
                        "match": BEFORE + r"-?0(?:[Nn][ghijefcpmdznuvt]?|[Ww][hijefcpmdznuvt]?)" + LITERAL_END,
                    },
                    {"name": "constant.language.boolean.q", "match": BEFORE + r"[01]+b" + LITERAL_END},
                    {"name": "constant.numeric.byte.q", "match": BEFORE + r"0x[0-9a-fA-F]*" + LITERAL_END},
                    {
                        "comment": "With p, a number is a timestamp that many hours past 2000: 1p. "
                        "As KDB-X reads them: a fraction takes e, f, n, t and p but no integer "
                        "letter (1.5i is an error); an exponent is a lower-case e, or an "
                        "unsigned upper-case one after a fraction (1.5E3, not 1E5 or 1.5E-3), "
                        "and takes only e or f after it. With c anything is a char, not a "
                        "number: 3c is \"3\".",
                        "name": "constant.numeric.q",
                        "match": BEFORE
                        + r"(?:(?:\d+\.\d*|\.\d+)(?:(?:e[+-]?\d+|E\d+)[ef]?|[efntp])?"
                        + r"|\d+(?:e[+-]?\d+[ef]?|[hijefnuvtp])?)"
                        + NUMBER_END,
                    },
                ],
            },
            "definition": {
                "patterns": [
                    {
                        "comment": "A name assigned a lambda: f:{...} or .ns.f::{...}.",
                        "match": BEFORE + SPLIT + r"\s*(::?)(?=\s*\{)",
                        "captures": {
                            "1": NAMESPACE,
                            "2": {"name": "entity.name.function.q"},
                            "3": {"name": "keyword.operator.assignment.q"},
                        },
                    },
                    {
                        "comment": "Any other assignment, a:1 or a::1, but not an iterator such as /: or \\:.",
                        "match": BEFORE + SPLIT + r"\s*(::?)(?![:/\\'])",
                        "captures": {
                            "1": NAMESPACE,
                            "2": {"name": "variable.other.definition.q"},
                            "3": {"name": "keyword.operator.assignment.q"},
                        },
                    },
                    {
                        "comment": "Amend in place, n+:1 or t,:row, which assigns as surely as n:1 does.",
                        "match": BEFORE + SPLIT + r"\s*([-+*%!&|^=<>~,#_$?@.]:)(?![:/\\'])",
                        "captures": {
                            "1": NAMESPACE,
                            "2": {"name": "variable.other.definition.q"},
                            "3": {"name": "keyword.operator.assignment.q"},
                        },
                    },
                ],
            },
            "flow": {
                "comment": "Return and signal, q's return and raise. Both open an expression; "
                "after an operand the same characters are each (f') and assignment (a:).",
                "patterns": [
                    {
                        "comment": "`:x` returns. `;:;` is the assignment function in @[d;i;:;v]. "
                        "\\G is where a lambda's parameter list ends: {[x]:x} returns too.",
                        "match": r"(?:^|\G|(?<=[\[;{]))\s*(:)(?![:/\\'])(?!\s*[;\]])",
                        "captures": {"1": {"name": "keyword.control.flow.return.q"}},
                    },
                    {
                        "comment": "`'x` signals. A space does not decide it - `{x} '[1 2]` is each. "
                        "Before a bracket or a closing parenthesis it is the iterator itself: "
                        "'[f;g] and (')[f;g] compose, and {'[`bad]} returns each of `bad, raising nothing.",
                        "match": r"(?:^|\G|(?<=[\[(;{:]))\s*(')(?![:/\\\[)])",
                        "captures": {"1": {"name": "keyword.control.flow.signal.q"}},
                    },
                ],
            },
            "keyword": {
                "patterns": [
                    {"name": "keyword.control.q", "match": words(CONTROL)},
                    {"name": "keyword.control.conditional.q", "match": r"\$(?=\[)"},
                    {"name": "keyword.other.qsql.q", "match": words(QSQL)},
                ],
            },
            "system-namespace": {
                "comment": "The namespaces q reserves for itself: .q .Q .z .h .j .o and their members.",
                "name": "support.function.system.q",
                "match": BEFORE + r"\.[qQzhjo](?:\.[A-Za-z0-9_]+)*" + AFTER,
            },
            "builtin": {"name": "support.function.builtin.q", "match": words(builtins)},
            "name": {
                "match": BEFORE + SPLIT + AFTER,
                "captures": {"1": NAMESPACE, "2": {"name": "variable.other.q"}},
            },
            "operator": {
                "patterns": [
                    {"name": "keyword.operator.iterator.q", "match": r"[/\\']:|':|'|/|\\"},
                    {"name": "keyword.operator.q", "match": r"[-+*%!&|^=<>~,#_$?@.:]"},
                    {"name": "punctuation.separator.statement.q", "match": ";"},
                ],
            },
        },
    }


if __name__ == "__main__":
    print(json.dumps(grammar(), indent=2))
